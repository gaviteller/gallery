/**
 * Scopes a Codex design stylesheet so it only affects one redesigned page.
 *
 * Codex's designs are standalone apps, so their CSS uses global selectors
 * (`.header`, `.sidebar`, `body`, `:root`...) that would clash with the rest of
 * the site. This prefixes every selector with a wrapper class, e.g. `.gx-feed`,
 * and turns `:root` / `html` / `body` rules into rules on the wrapper itself.
 *
 * Usage:  node scripts/scope-design-css.mjs <input.css> <output.css> <wrapperClass>
 * Re-run it whenever Codex sends an updated design; never hand-edit the output.
 */
import { readFileSync, writeFileSync } from "node:fs"
import postcss from "postcss"

const [inputPath, outputPath, wrapperClass] = process.argv.slice(2)
if (!inputPath || !outputPath || !wrapperClass) {
  console.error("Usage: node scripts/scope-design-css.mjs <input.css> <output.css> <wrapperClass>")
  process.exit(1)
}
const wrapper = `.${wrapperClass}`

function scopeSelector(selector) {
  const trimmed = selector.trim()
  if (/^(:root|html|body)$/.test(trimmed)) return wrapper
  // "html body .x" / "body .x" → ".gx-page .x"
  const withoutRoots = trimmed.replace(/^(html\s+)?(body|:root)\s+/, "")
  if (withoutRoots !== trimmed) return `${wrapper} ${withoutRoots}`
  if (trimmed === "*") return `${wrapper}, ${wrapper} *`
  return `${wrapper} ${trimmed}`
}

const root = postcss.parse(readFileSync(inputPath, "utf8"))
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return
  rule.selectors = rule.selectors.map(scopeSelector)
})

const header = `/* GENERATED by scripts/scope-design-css.mjs from a Codex design — do not edit by hand. Scope: ${wrapper} */\n`
writeFileSync(outputPath, header + root.toString())
console.log(`Scoped ${inputPath} → ${outputPath} under ${wrapper}`)
